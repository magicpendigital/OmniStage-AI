#!/usr/bin/env node
/**
 * Phase 7 — bundles the OmniStage Player (src/player/entry.ts + the shared runtime + Three.js) into one IIFE that
 * every export inlines: src/exporter/generated/playerRuntime.ts. Regenerate after changing src/player, src/runtime
 * or anything they import:   npm run build:player
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Builds the Player bundle in memory (also used by tests/player.test.ts to check the generated file is fresh). */
export async function buildPlayer() {
  const result = await build({
  entryPoints: [resolve(root, 'src/player/entry.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'OmniPlayer',
  platform: 'browser',
  target: 'es2019',
  write: false,
  legalComments: 'none',
  metafile: true,
  define: { 'import.meta.hot': 'undefined', 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
  });
  const code = result.outputFiles[0].text.trim();
  const hash = createHash('sha256').update(code).digest('hex').slice(0, 12);
  return { code, hash, metafile: result.metafile };
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
const { code, hash, metafile } = await buildPlayer();
const inputs = Object.entries(metafile.inputs).sort((a, b) => b[1].bytes - a[1].bytes).slice(0, 6);
const out = resolve(root, 'src/exporter/generated/playerRuntime.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-player.mjs — do not edit. Includes Three.js (MIT License, three.js authors).\n` +
    `export const PLAYER_RUNTIME_VERSION = ${JSON.stringify(hash)};\n` +
    `export const PLAYER_RUNTIME = ${JSON.stringify(code)};\n`
);
console.log(`OmniStage Player ${hash}: ${(code.length / 1024).toFixed(1)} KB`);
for (const [file, info] of inputs) console.log(`  ${(info.bytes / 1024).toFixed(0).padStart(5)} KB  ${file}`);
}
