#!/usr/bin/env node
/**
 * Builds the tree-shaken Three.js runtime that gets inlined into exported playable ads, so 3D exports run
 * offline (no CDN). Output: src/exporter/generated/threePlayableRuntime.ts (committed, regenerate after
 * upgrading `three` or using a new THREE class in the exporter's inline script):
 *
 *   node scripts/build-playable-three.mjs
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Every THREE.* symbol the exporter's inline runtime uses (tests/playableExport.test.ts checks this list). */
export const PLAYABLE_THREE_EXPORTS = [
  'REVISION', 'WebGLRenderer', 'Scene', 'PerspectiveCamera', 'Color', 'Fog',
  'HemisphereLight', 'DirectionalLight', 'AmbientLight', 'PointLight',
  'PlaneGeometry', 'BoxGeometry', 'SphereGeometry', 'CylinderGeometry', 'ConeGeometry', 'OctahedronGeometry',
  'TorusGeometry', 'CapsuleGeometry', 'MeshStandardMaterial', 'MeshBasicMaterial', 'Mesh', 'Group', 'GridHelper',
  'Vector2', 'Vector3', 'Raycaster', 'Clock', 'DoubleSide',
];

const result = await build({
  stdin: {
    contents: `export { ${PLAYABLE_THREE_EXPORTS.join(', ')} } from 'three';`,
    resolveDir: root,
    loader: 'js',
  },
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'THREE',
  target: 'es2018',
  write: false,
  legalComments: 'none',
});

const code = result.outputFiles[0].text.trim();
const { REVISION } = await import('three');
const out = resolve(root, 'src/exporter/generated/threePlayableRuntime.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-playable-three.mjs — do not edit. Three.js r${REVISION} (MIT License, three.js authors).\n` +
    `export const THREE_PLAYABLE_REVISION = ${JSON.stringify(REVISION)};\n` +
    `export const THREE_PLAYABLE_EXPORTS = ${JSON.stringify(PLAYABLE_THREE_EXPORTS)};\n` +
    `export const THREE_PLAYABLE_RUNTIME = ${JSON.stringify(code)};\n`
);
console.log(`three r${REVISION} playable runtime: ${(code.length / 1024).toFixed(1)} KB -> ${out}`);
