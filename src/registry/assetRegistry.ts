export function cloneSceneSpec(spec: SceneSpec): SceneSpec {
  const cloned = JSON.parse(JSON.stringify(spec)) as SceneSpec;
  if (!cloned.engineType) cloned.engineType = '3d';
  if (!cloned.world) cloned.world = JSON.parse(JSON.stringify(DEFAULT_WORLD_SPEC));
  if (!Array.isArray(cloned.nodes2D)) cloned.nodes2D = [];
  return cloned;
}
